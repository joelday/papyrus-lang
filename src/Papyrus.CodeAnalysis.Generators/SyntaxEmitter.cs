using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Papyrus.CodeAnalysis.Generators;

internal static class SyntaxEmitter
{
    internal static void Emit(
        SourceProductionContext context,
        ImmutableArray<KindModel> tokens,
        ImmutableArray<KindModel> trivia,
        ImmutableArray<KindModel> nodes)
    {
        var kinds = new List<KindModel>(tokens.Length + trivia.Length + nodes.Length);
        kinds.AddRange(trivia);
        kinds.AddRange(tokens);
        kinds.AddRange(nodes);
        kinds.Sort(CompareKinds);

        context.AddSource("SyntaxKind.g.cs", SourceText.From(EmitSyntaxKind(kinds), Encoding.UTF8));
        context.AddSource("SyntaxFacts.g.cs", SourceText.From(EmitSyntaxFacts(kinds), Encoding.UTF8));

        var nodeKinds = new List<KindModel>();
        foreach (var kind in kinds)
        {
            if (kind.Category == KindCategory.Node)
            {
                nodeKinds.Add(kind);
            }
        }

        if (nodeKinds.Count > 0)
        {
            context.AddSource(
                "InternalSyntax.Nodes.g.cs",
                SourceText.From(EmitGreenNodes(nodeKinds), Encoding.UTF8));
            context.AddSource(
                "Syntax.Nodes.g.cs",
                SourceText.From(EmitRedNodes(nodeKinds), Encoding.UTF8));
            context.AddSource(
                "SyntaxFactory.g.cs",
                SourceText.From(EmitFactory(nodeKinds), Encoding.UTF8));
        }
    }

    private static string EmitSyntaxKind(List<KindModel> kinds)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Papyrus.CodeAnalysis.Syntax;");
        builder.AppendLine();
        builder.AppendLine("public enum SyntaxKind : ushort");
        builder.AppendLine("{");
        builder.AppendLine("    None = 0,");
        builder.AppendLine("    List = 1,");

        var value = 2;
        var lastCategory = (KindCategory?)null;
        foreach (var kind in kinds)
        {
            if (lastCategory != kind.Category)
            {
                builder.AppendLine();
                lastCategory = kind.Category;
            }

            builder.Append("    ");
            builder.Append(kind.Name);
            builder.Append(" = ");
            builder.Append(value);
            builder.AppendLine(",");
            value++;
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string EmitSyntaxFacts(List<KindModel> kinds)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Papyrus.CodeAnalysis.Syntax;");
        builder.AppendLine();
        builder.AppendLine("public static partial class SyntaxFacts");
        builder.AppendLine("{");
        AppendPredicate(builder, "IsKeyword", kinds, static kind => kind.Category == KindCategory.Keyword);
        builder.AppendLine();
        AppendPredicate(builder, "IsTrivia", kinds, static kind => kind.Category == KindCategory.Trivia);
        builder.AppendLine();
        AppendPredicate(
            builder,
            "IsToken",
            kinds,
            static kind => kind.Category == KindCategory.Token || kind.Category == KindCategory.Keyword);
        builder.AppendLine();
        AppendGetText(builder, kinds);
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendPredicate(
        StringBuilder builder,
        string methodName,
        List<KindModel> kinds,
        Func<KindModel, bool> include)
    {
        builder.Append("    public static bool ");
        builder.Append(methodName);
        builder.AppendLine("(SyntaxKind kind)");
        builder.AppendLine("    {");
        builder.AppendLine("        switch (kind)");
        builder.AppendLine("        {");

        var any = false;
        foreach (var kind in kinds)
        {
            if (!include(kind))
            {
                continue;
            }

            any = true;
            builder.Append("            case SyntaxKind.");
            builder.Append(kind.Name);
            builder.AppendLine(":");
        }

        if (any)
        {
            builder.AppendLine("                return true;");
        }

        builder.AppendLine("            default:");
        builder.AppendLine("                return false;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static void AppendGetText(StringBuilder builder, List<KindModel> kinds)
    {
        builder.AppendLine("    public static string? GetText(SyntaxKind kind)");
        builder.AppendLine("    {");
        builder.AppendLine("        switch (kind)");
        builder.AppendLine("        {");

        foreach (var kind in kinds)
        {
            if (kind.Text is null)
            {
                continue;
            }

            builder.Append("            case SyntaxKind.");
            builder.Append(kind.Name);
            builder.Append(": return \"");
            builder.Append(Escape(kind.Text));
            builder.AppendLine("\";");
        }

        builder.AppendLine("            default: return null;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
    }

    private static string Escape(string text)
    {
        return text
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"");
    }

    private static int CompareKinds(KindModel left, KindModel right)
    {
        var category = left.Category.CompareTo(right.Category);
        if (category != 0)
        {
            return category;
        }

        return string.CompareOrdinal(left.Name, right.Name);
    }

    private static string EmitGreenNodes(List<KindModel> nodes)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using Papyrus.CodeAnalysis;");
        builder.AppendLine();
        builder.AppendLine("namespace Papyrus.CodeAnalysis.Syntax.InternalSyntax;");
        builder.AppendLine();

        for (var n = 0; n < nodes.Count; n++)
        {
            if (n > 0)
            {
                builder.AppendLine();
            }

            var node = nodes[n];
            var typeName = NodeTypeName(node);
            builder.Append("internal sealed class ");
            builder.Append(typeName);
            builder.AppendLine(" : GreenNode");
            builder.AppendLine("{");

            foreach (var child in node.Children)
            {
                builder.Append("    internal readonly GreenNode? ");
                builder.Append(child.Name);
                builder.AppendLine(";");
            }

            if (node.Children.Length > 0)
            {
                builder.AppendLine();
            }

            builder.Append("    internal ");
            builder.Append(typeName);
            builder.Append("(");
            AppendGreenParameters(builder, node);
            builder.AppendLine(")");
            builder.Append("        : base(SyntaxKind.");
            builder.Append(node.Name);
            builder.Append(", ComputeWidth(");
            AppendChildNames(builder, node, camelCase: true);
            builder.Append("), ComputeFlags(diagnostics");
            if (node.Children.Length > 0)
            {
                builder.Append(", ");
                AppendChildNames(builder, node, camelCase: true);
            }

            builder.AppendLine("), diagnostics)");
            builder.AppendLine("    {");
            foreach (var child in node.Children)
            {
                builder.Append("        ");
                builder.Append(child.Name);
                builder.Append(" = ");
                builder.Append(ToCamelCase(child.Name));
                builder.AppendLine(";");
            }

            builder.AppendLine("    }");
            builder.AppendLine();
            builder.Append("    internal override int SlotCount => ");
            builder.Append(node.Children.Length);
            builder.AppendLine(";");
            builder.AppendLine();
            builder.AppendLine("    internal override GreenNode? GetSlot(int index)");
            builder.AppendLine("    {");
            if (node.Children.Length == 0)
            {
                builder.AppendLine("        return null;");
            }
            else
            {
                builder.AppendLine("        switch (index)");
                builder.AppendLine("        {");
                for (var i = 0; i < node.Children.Length; i++)
                {
                    builder.Append("            case ");
                    builder.Append(i);
                    builder.Append(": return ");
                    builder.Append(node.Children[i].Name);
                    builder.AppendLine(";");
                }

                builder.AppendLine("            default: return null;");
                builder.AppendLine("        }");
            }

            builder.AppendLine("    }");
            builder.AppendLine();
            builder.AppendLine("    internal override SyntaxNode CreateRed(SyntaxNode? parent, int position)");
            builder.AppendLine("    {");
            builder.Append("        return new Papyrus.CodeAnalysis.Syntax.");
            builder.Append(typeName);
            builder.AppendLine("(this, parent, position);");
            builder.AppendLine("    }");
            builder.AppendLine();
            builder.AppendLine("    internal override GreenNode WithDiagnostics(DiagnosticInfo[]? diagnostics)");
            builder.AppendLine("    {");
            builder.Append("        return new ");
            builder.Append(typeName);
            builder.Append("(");
            AppendChildNames(builder, node);
            if (node.Children.Length > 0)
            {
                builder.Append(", ");
            }

            builder.AppendLine("diagnostics);");
            builder.AppendLine("    }");
            builder.AppendLine();
            builder.Append("    internal ");
            builder.Append(typeName);
            builder.Append(" Update(");
            AppendGreenParameters(builder, node, includeDiagnostics: false);
            builder.AppendLine(")");
            builder.AppendLine("    {");
            if (node.Children.Length == 0)
            {
                builder.AppendLine("        return this;");
            }
            else
            {
                builder.Append("        if (");
                for (var i = 0; i < node.Children.Length; i++)
                {
                    if (i > 0)
                    {
                        builder.Append(" && ");
                    }

                    builder.Append(ToCamelCase(node.Children[i].Name));
                    builder.Append(" == ");
                    builder.Append(node.Children[i].Name);
                }

                builder.AppendLine(")");
                builder.AppendLine("        {");
                builder.AppendLine("            return this;");
                builder.AppendLine("        }");
                builder.AppendLine();
                builder.Append("        return new ");
                builder.Append(typeName);
                builder.Append("(");
                AppendChildNames(builder, node, camelCase: true);
                builder.AppendLine(", GetDiagnostics());");
            }

            builder.AppendLine("    }");
            builder.AppendLine();
            builder.Append("    private static int ComputeWidth(");
            AppendGreenParameters(builder, node, includeDiagnostics: false);
            builder.AppendLine(")");
            builder.AppendLine("    {");
            builder.AppendLine("        var width = 0;");
            foreach (var child in node.Children)
            {
                var camel = ToCamelCase(child.Name);
                builder.Append("        if (");
                builder.Append(camel);
                builder.AppendLine(" is not null)");
                builder.AppendLine("        {");
                builder.Append("            width += ");
                builder.Append(camel);
                builder.AppendLine(".FullWidth;");
                builder.AppendLine("        }");
            }

            builder.AppendLine("        return width;");
            builder.AppendLine("    }");
            builder.AppendLine();
            builder.Append("    private static NodeFlags ComputeFlags(DiagnosticInfo[]? diagnostics");
            if (node.Children.Length > 0)
            {
                builder.Append(", ");
                AppendGreenParameters(builder, node, includeDiagnostics: false);
            }

            builder.AppendLine(")");
            builder.AppendLine("    {");
            builder.AppendLine("        var nodeFlags = diagnostics is { Length: > 0 } ? NodeFlags.ContainsDiagnostics : NodeFlags.None;");
            builder.AppendLine("        var present = 0;");
            builder.AppendLine("        var missing = 0;");
            foreach (var child in node.Children)
            {
                builder.Append("        GreenNode.IncludeChild(ref nodeFlags, ref present, ref missing, ");
                builder.Append(ToCamelCase(child.Name));
                builder.AppendLine(");");
            }

            builder.AppendLine("        return GreenNode.FinishFlags(nodeFlags, present, missing);");
            builder.AppendLine("    }");
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    private static string EmitRedNodes(List<KindModel> nodes)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Papyrus.CodeAnalysis.Syntax;");
        builder.AppendLine();

        for (var n = 0; n < nodes.Count; n++)
        {
            if (n > 0)
            {
                builder.AppendLine();
            }

            var node = nodes[n];
            var typeName = NodeTypeName(node);
            builder.Append("internal sealed partial class ");
            builder.Append(typeName);
            builder.AppendLine();
            builder.AppendLine("{");
            builder.Append("    internal ");
            builder.Append(typeName);
            builder.Append("(InternalSyntax.");
            builder.Append(typeName);
            builder.AppendLine(" green, SyntaxNode? parent, int position)");
            builder.AppendLine("        : base(green, parent, position)");
            builder.AppendLine("    {");
            var hasTokenChild = false;
            foreach (var child in node.Children)
            {
                if (child.IsToken)
                {
                    hasTokenChild = true;
                    break;
                }
            }

            if (hasTokenChild)
            {
                builder.AppendLine("        var current = position;");
            }

            for (var i = 0; i < node.Children.Length; i++)
            {
                var child = node.Children[i];
                var field = "green." + child.Name;
                if (child.IsToken)
                {
                    builder.Append("        ");
                    builder.Append(child.Name);
                    builder.Append(" = new SyntaxToken(");
                    builder.Append(field);
                    builder.AppendLine(", this, current);");
                }

                if (hasTokenChild && i + 1 < node.Children.Length)
                {
                    builder.Append("        current += ");
                    builder.Append(field);
                    builder.AppendLine("?.FullWidth ?? 0;");
                }
            }

            builder.AppendLine("    }");

            for (var i = 0; i < node.Children.Length; i++)
            {
                var child = node.Children[i];
                if (child.IsToken)
                {
                    continue;
                }

                builder.AppendLine();
                if (child.IsList)
                {
                    builder.Append("    public partial ");
                    builder.Append(child.TypeName);
                    builder.Append(" ");
                    builder.Append(child.Name);
                    builder.AppendLine();
                    builder.AppendLine("    {");
                    builder.Append("        get => GetRedList<");
                    builder.Append(child.ElementTypeName);
                    builder.Append(">(");
                    builder.Append(i);
                    builder.AppendLine(");");
                    builder.AppendLine("    }");
                    continue;
                }

                builder.Append("    private ");
                builder.Append(child.TypeName);
                builder.Append("? _");
                builder.Append(ToCamelCase(child.Name));
                builder.AppendLine(";");
                builder.Append("    public partial ");
                builder.Append(RedParameterType(child));
                builder.Append(" ");
                builder.Append(child.Name);
                builder.AppendLine();
                builder.AppendLine("    {");
                builder.Append("        get => GetRed<");
                builder.Append(child.TypeName);
                builder.Append(">(");
                builder.Append(i);
                builder.Append(")");
                if (!child.IsOptional)
                {
                    builder.Append("!");
                }

                builder.AppendLine(";");
                builder.AppendLine("    }");
            }
            builder.AppendLine();
            builder.Append("    public ");
            builder.Append(typeName);
            builder.Append(" Update(");
            AppendRedParameters(builder, node);
            builder.AppendLine(")");
            builder.AppendLine("    {");
            builder.Append("        var green = (InternalSyntax.");
            builder.Append(typeName);
            builder.AppendLine(")Green;");
            builder.Append("        var updated = green.Update(");
            for (var i = 0; i < node.Children.Length; i++)
            {
                if (i > 0)
                {
                    builder.Append(", ");
                }

                var child = node.Children[i];
                var camel = ToCamelCase(child.Name);
                if (child.IsToken || child.IsList)
                {
                    builder.Append(camel);
                    builder.Append(".Node");
                }
                else
                {
                    builder.Append(camel);
                    builder.Append("?.Green");
                }
            }

            builder.AppendLine(");");
            builder.AppendLine("        if (object.ReferenceEquals(updated, green))");
            builder.AppendLine("        {");
            builder.AppendLine("            return this;");
            builder.AppendLine("        }");
            builder.AppendLine();
            builder.Append("        return (");
            builder.Append(typeName);
            builder.AppendLine(")updated.CreateRed(Parent, Position);");
            builder.AppendLine("    }");

            foreach (var child in node.Children)
            {
                builder.AppendLine();
                builder.Append("    public ");
                builder.Append(typeName);
                builder.Append(" With");
                builder.Append(child.Name);
                builder.Append("(");
                builder.Append(RedParameterType(child));
                builder.Append(" ");
                builder.Append(ToCamelCase(child.Name));
                builder.AppendLine(")");
                builder.Append("        => Update(");
                for (var i = 0; i < node.Children.Length; i++)
                {
                    if (i > 0)
                    {
                        builder.Append(", ");
                    }

                    var current = node.Children[i];
                    builder.Append(current.Name == child.Name ? ToCamelCase(current.Name) : current.Name);
                }

                builder.AppendLine(");");
            }

            builder.AppendLine();
            builder.AppendLine("    public override SyntaxNode? GetCachedSlot(int index)");
            builder.AppendLine("    {");
            var hasNodeChildren = false;
            foreach (var child in node.Children)
            {
                if (!child.IsToken && !child.IsList)
                {
                    hasNodeChildren = true;
                    break;
                }
            }

            if (!hasNodeChildren)
            {
                builder.AppendLine("        return null;");
            }
            else
            {
                builder.AppendLine("        switch (index)");
                builder.AppendLine("        {");
                for (var i = 0; i < node.Children.Length; i++)
                {
                    if (node.Children[i].IsToken || node.Children[i].IsList)
                    {
                        continue;
                    }

                    builder.Append("            case ");
                    builder.Append(i);
                    builder.Append(": return _");
                    builder.Append(ToCamelCase(node.Children[i].Name));
                    builder.AppendLine(";");
                }

                builder.AppendLine("            default: return null;");
                builder.AppendLine("        }");
            }

            builder.AppendLine("    }");
            builder.AppendLine();
            builder.AppendLine("    public override void SetCachedSlot(int index, SyntaxNode node)");
            builder.AppendLine("    {");
            if (!hasNodeChildren)
            {
                builder.AppendLine("    }");
            }
            else
            {
                builder.AppendLine("        switch (index)");
                builder.AppendLine("        {");
                for (var i = 0; i < node.Children.Length; i++)
                {
                    if (node.Children[i].IsToken || node.Children[i].IsList)
                    {
                        continue;
                    }

                    builder.Append("            case ");
                    builder.Append(i);
                    builder.AppendLine(":");
                    builder.Append("                _");
                    builder.Append(ToCamelCase(node.Children[i].Name));
                    builder.Append(" = (");
                    builder.Append(node.Children[i].TypeName);
                    builder.AppendLine(")node;");
                    builder.AppendLine("                break;");
                }

                builder.AppendLine("        }");
                builder.AppendLine("    }");
            }
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    private static string EmitFactory(List<KindModel> nodes)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("namespace Papyrus.CodeAnalysis.Syntax;");
        builder.AppendLine();
        builder.AppendLine("internal static partial class SyntaxFactory");
        builder.AppendLine("{");

        for (var n = 0; n < nodes.Count; n++)
        {
            if (n > 0)
            {
                builder.AppendLine();
            }

            var node = nodes[n];
            var typeName = NodeTypeName(node);
            builder.Append("    public static ");
            builder.Append(typeName);
            builder.Append(" ");
            builder.Append(node.Name);
            builder.Append("(");
            AppendRedParameters(builder, node, nullableNodes: true);
            builder.AppendLine(")");
            builder.AppendLine("    {");
            builder.Append("        var green = new InternalSyntax.");
            builder.Append(typeName);
            builder.Append("(");
            for (var i = 0; i < node.Children.Length; i++)
            {
                if (i > 0)
                {
                    builder.Append(", ");
                }

                var child = node.Children[i];
                var camel = ToCamelCase(child.Name);
                if (child.IsToken || child.IsList)
                {
                    builder.Append(camel);
                    builder.Append(".Node");
                }
                else
                {
                    builder.Append(camel);
                    builder.Append("?.Green");
                }
            }

            builder.AppendLine(");");
            builder.Append("        return (");
            builder.Append(typeName);
            builder.AppendLine(")green.CreateRed(parent: null, position: 0);");
            builder.AppendLine("    }");
        }

        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string NodeTypeName(KindModel node)
        => string.IsNullOrEmpty(node.TypeName) ? node.Name + "Syntax" : node.TypeName;

    private static void AppendGreenParameters(StringBuilder builder, KindModel node, bool includeDiagnostics = true)
    {
        for (var i = 0; i < node.Children.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append("GreenNode? ");
            builder.Append(ToCamelCase(node.Children[i].Name));
        }

        if (includeDiagnostics)
        {
            if (node.Children.Length > 0)
            {
                builder.Append(", ");
            }

            builder.Append("DiagnosticInfo[]? diagnostics = null");
        }
    }

    private static void AppendChildNames(StringBuilder builder, KindModel node, bool camelCase = false)
    {
        for (var i = 0; i < node.Children.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            builder.Append(camelCase ? ToCamelCase(node.Children[i].Name) : node.Children[i].Name);
        }
    }

    private static void AppendRedParameters(StringBuilder builder, KindModel node, bool nullableNodes = false)
    {
        for (var i = 0; i < node.Children.Length; i++)
        {
            if (i > 0)
            {
                builder.Append(", ");
            }

            var child = node.Children[i];
            builder.Append(nullableNodes ? FactoryParameterType(child) : RedParameterType(child));
            builder.Append(" ");
            builder.Append(ToCamelCase(child.Name));
        }
    }

    private static string RedParameterType(ChildSlot child)
    {
        if (child.IsToken)
        {
            return "SyntaxToken";
        }

        return child.IsOptional ? child.TypeName + "?" : child.TypeName;
    }

    private static string FactoryParameterType(ChildSlot child)
    {
        if (child.IsToken)
        {
            return "SyntaxToken";
        }

        return child.IsOptional ? child.TypeName + "?" : child.TypeName;
    }

    private static string ToCamelCase(string name)
    {
        if (name.Length == 0 || char.IsLower(name[0]))
        {
            return name;
        }

        if (name.Length == 1)
        {
            return name.ToLowerInvariant();
        }

        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }
}
